#!/usr/bin/env node
/**
 * DigiLegacy contract compiler.
 *
 * Single source: contracts/commands.json, errors.json, tools.json, schemas/, mocks.json.
 * Generates seven consumer stubs so IPC/dispatch/CLI/HTTP/MCP/mock/tools cannot drift:
 *   1. web/src/platform/generated/ipc.ts
 *   2. core/contracts/src/generated.rs
 *   3. apps/cli/src/generated.rs
 *   4. apps/server/src/generated.rs
 *   5. apps/mcp/tools.generated.json
 *   6. web/src/platform/generated/mock.ts
 *   7. contracts/generated/tool-manifest.json
 *
 * Also derives contracts/openapi.json from command HTTP transports.
 *
 * Usage:
 *   node tools/generate.mjs
 *   node tools/generate.mjs --check
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import fsSync from "node:fs";
import os from "node:os";
import { spawnSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const HEADER = "// @generated by tools/generate.mjs — do not edit. Run `npm run contracts:generate` in web/.\n";

function readJson(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));
}

function rustfmt(content) {
  const bin = process.env.RUSTFMT_BIN || (fsSync.existsSync(`${process.env.HOME}/.cargo/bin/rustfmt`) ? `${process.env.HOME}/.cargo/bin/rustfmt` : "rustfmt");
  const temp = path.join(os.tmpdir(), `digilegacy-${process.pid}-${Math.random().toString(16).slice(2)}.rs`);
  fsSync.writeFileSync(temp, content);
  const result = spawnSync(bin, ["--edition", "2021", temp], { encoding: "utf8" });
  const formatted = result.status === 0 ? fsSync.readFileSync(temp, "utf8") : content;
  fsSync.rmSync(temp, { force: true });
  return formatted;
}

function canonical(rel, content) {
  return rel.endsWith(".rs") ? rustfmt(content) : content;
}

function write(rel, content) {
  const target = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const canonicalContent = canonical(rel, content);
  const previousRaw = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  const previous = previousRaw === null ? null : canonical(rel, previousRaw);
  if (CHECK) {
    if (previous !== canonicalContent) {
      console.error(`contract drift: ${rel}`);
      process.exitCode = 1;
    }
    return;
  }
  if (previousRaw !== canonicalContent) {
    fs.writeFileSync(target, canonicalContent);
    console.log(`generated ${rel}`);
  }
}

function camel(name) {
  return name
    .split(".")
    .map((part, index) =>
      index === 0 ? part.charAt(0).toLowerCase() + part.slice(1) : part.charAt(0).toUpperCase() + part.slice(1),
    )
    .join("");
}

function rstr(value) {
  return JSON.stringify(value);
}

const commands = readJson("contracts/commands.json");
const errors = readJson("contracts/errors.json");
const tools = readJson("contracts/tools.json");
const mocks = readJson("contracts/mocks.json").data;

const commandList = commands.commands;
const commandNames = new Set();
const errorCodes = new Set(errors.errors.map((e) => e.code));
const domains = new Set([
  "app", "assets", "platform", "plan", "trigger", "deliver", "review", "drill",
  "security", "backup", "checkpoint", "connections", "llm", "agent",
  "policy_sync", "mail", "heartbeat", "diagnostics", "settings",
]);
const permissions = new Set(["read", "draft", "write", "key", "network", "desktop"]);

for (const command of commandList) {
  if (commandNames.has(command.name)) throw new Error(`duplicate command: ${command.name}`);
  commandNames.add(command.name);
  if (!domains.has(command.domain)) throw new Error(`unknown domain: ${command.domain} in ${command.name}`);
  if (!permissions.has(command.permission)) throw new Error(`unknown permission: ${command.permission}`);
  for (const file of [command.input, command.output]) {
    if (!fs.existsSync(path.join(ROOT, "contracts", file))) throw new Error(`missing schema: ${file}`);
  }
  for (const code of command.errors) {
    if (!errorCodes.has(code)) throw new Error(`unknown error ${code} in ${command.name}`);
  }
  const http = command.transports.http;
  if (!http || !/^(GET|POST|PATCH|PUT|DELETE) \/api\/v1\//.test(http)) {
    throw new Error(`command ${command.name} has invalid http transport: ${http}`);
  }
}

for (const tool of tools.tools) {
  const command = commandList.find((item) => item.name === tool.human_equivalent);
  if (!command) throw new Error(`tool ${tool.name} references unknown command ${tool.human_equivalent}`);
  if (tool.permission !== command.permission) {
    throw new Error(`tool ${tool.name} permission ${tool.permission} != command ${command.name} permission ${command.permission}`);
  }
  if (command.permission === "write" && tool.approval !== "required") {
    throw new Error(`write tool ${tool.name} must require approval`);
  }
  if (tool.mcp && command.permission !== "read" && command.permission !== "draft") {
    throw new Error(`MCP tool ${tool.name} must be read or draft`);
  }
}

const commandToTool = new Map(tools.tools.map((tool) => [tool.human_equivalent, tool.name]));

const tsCommands = commandList
  .map((command) => `  ${camel(command.name)}: ${rstr(command.name)},`)
  .join("\n");
const permissionEntries = commandList
  .map((command) => `  ${rstr(command.name)}: ${rstr(command.permission)},`)
  .join("\n");
const httpEntries = commandList
  .map((command) => `  ${rstr(command.name)}: ${rstr(command.transports.http)},`)
  .join("\n");
const unlockEntries = commandList
  .map((command) => `  ${rstr(command.name)}: ${command.requiresUnlock},`)
  .join("\n");
const auditEntries = commandList
  .map((command) => `  ${rstr(command.name)}: ${command.audit},`)
  .join("\n");
const toolEntries = commandList
  .map((command) => `  ${rstr(command.name)}: ${rstr(commandToTool.get(command.name) ?? null)},`)
  .join("\n");

write(
  "web/src/platform/generated/ipc.ts",
  `${HEADER}
export type Permission = "read" | "draft" | "write" | "key" | "network" | "desktop";

export const INVOKE_PATH = "/api/v1/invoke";
export const COMMANDS = {
${tsCommands}
} as const;

export type CommandName = (typeof COMMANDS)[keyof typeof COMMANDS];

export const COMMAND_PERMISSION: Record<CommandName, Permission> = {
${permissionEntries}
};

export const COMMAND_HTTP: Record<CommandName, string> = {
${httpEntries}
};

export const COMMAND_REQUIRES_UNLOCK: Record<CommandName, boolean> = {
${unlockEntries}
};

export const COMMAND_AUDIT: Record<CommandName, boolean> = {
${auditEntries}
};

export const COMMAND_TOOL: Record<CommandName, string | null> = {
${toolEntries}
};

export const COMMAND_NAMES = Object.values(COMMANDS);
`,
);

const rustErrorRows = errors.errors
  .map(
    (error) =>
      `    ErrorSpec { code: ${rstr(error.code)}, http: ${error.http}, retryable: ${error.retryable}, cli_exit: ${error.cliExit}, message_key: ${rstr(error.messageKey)} },`,
  )
  .join("\n");

write(
  "core/contracts/src/errors.rs",
  `// @generated by tools/generate.mjs — do not edit.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ErrorSpec {
    pub code: &'static str,
    pub http: u16,
    pub retryable: bool,
    pub cli_exit: i32,
    pub message_key: &'static str,
}

pub const ERRORS: &[ErrorSpec] = &[
${rustErrorRows}
];

pub fn find(code: &str) -> Option<&'static ErrorSpec> {
    ERRORS.iter().find(|error| error.code == code)
}
`,
);

const rustCommandRows = commandList
  .map(
    (command) =>
      `    CommandSpec { name: ${rstr(command.name)}, domain: ${rstr(command.domain)}, permission: ${rstr(command.permission)}, http: ${rstr(command.transports.http)}, requires_unlock: ${command.requiresUnlock}, audit: ${command.audit} },`,
  )
  .join("\n");

write(
  "core/contracts/src/generated.rs",
  `// @generated by tools/generate.mjs — do not edit.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CommandSpec {
    pub name: &'static str,
    pub domain: &'static str,
    pub permission: &'static str,
    pub http: &'static str,
    pub requires_unlock: bool,
    pub audit: bool,
}

pub const COMMANDS: &[CommandSpec] = &[
${rustCommandRows}
];

pub fn find(name: &str) -> Option<&'static CommandSpec> {
    COMMANDS.iter().find(|command| command.name == name)
}

pub fn names() -> impl Iterator<Item = &'static str> {
    COMMANDS.iter().map(|command| command.name)
}
`,
);

const cliRows = commandList
  .map((command) => `    ${rstr(command.transports.cli)},`)
  .join("\n");
write(
  "apps/cli/src/generated.rs",
  `// @generated by tools/generate.mjs — do not edit.

pub const COMMAND_LINES: &[&str] = &[
${cliRows}
];

pub fn print_help() {
    println!("DigiLegacy CLI (M0 skeleton)");
    println!("Commands:");
    for line in COMMAND_LINES {
        println!("  {line}");
    }
    println!("\\nUse digilegacy-cli commands --json for the machine-readable manifest.");
}
`,
);

const serverRows = commandList
  .map(
    (command) =>
      `    CommandSpec { name: ${rstr(command.name)}, domain: ${rstr(command.domain)}, permission: ${rstr(command.permission)}, http: ${rstr(command.transports.http)}, requires_unlock: ${command.requiresUnlock}, audit: ${command.audit} },`,
  )
  .join("\n");
write(
  "apps/server/src/generated.rs",
  `// @generated by tools/generate.mjs — do not edit.

#[derive(Debug, Clone, Copy)]
pub struct CommandSpec {
    pub name: &'static str,
    pub domain: &'static str,
    pub permission: &'static str,
    pub http: &'static str,
    pub requires_unlock: bool,
    pub audit: bool,
}

pub const COMMANDS: &[CommandSpec] = &[
${serverRows}
];

pub fn find(name: &str) -> Option<&'static CommandSpec> {
    COMMANDS.iter().find(|command| command.name == name)
}
`,
);

const mcpTools = tools.tools
  .filter((tool) => tool.mcp)
  .map((tool) => ({
    name: tool.name,
    title: tool.title,
    description: tool.description,
    inputSchema: readJson(path.join("contracts", tool.input_schema)),
    annotations: {
      readOnlyHint: tool.permission === "read",
      destructiveHint: tool.permission === "write",
      idempotentHint: tool.idempotent,
    },
  }));
write("apps/mcp/tools.generated.json", JSON.stringify(mcpTools, null, 2) + "\n");

const mockValue = {};
for (const command of commandList) {
  if (Object.prototype.hasOwnProperty.call(mocks, command.name)) {
    mockValue[command.name] = mocks[command.name];
  }
}
write(
  "web/src/platform/generated/mock.ts",
  `${HEADER}
import type { CommandName } from "./ipc";

const MOCK_DATA: Record<string, unknown> = ${JSON.stringify(mockValue, null, 2)};

export function mockInvoke(name: CommandName): unknown {
  const value = MOCK_DATA[name];
  if (value === undefined) {
    return null;
  }
  return JSON.parse(JSON.stringify(value)) as unknown;
}
`,
);

const toolTsRows = tools.tools
  .map(
    (tool) =>
      `  { name: ${rstr(tool.name)}, title: ${rstr(tool.title)}, description: ${rstr(tool.description)}, permission: ${rstr(tool.permission)}, approval: ${rstr(tool.approval)}, audit: ${tool.audit}, mcp: ${tool.mcp}, humanEquivalent: ${rstr(tool.human_equivalent)} },`,
  )
  .join("\n");
write(
  "web/src/platform/generated/tools.ts",
  `${HEADER}
export interface ToolCatalogItem {
  name: string;
  title: string;
  description: string;
  permission: string;
  approval: string;
  audit: boolean;
  mcp: boolean;
  humanEquivalent: string;
}

export const TOOL_CATALOG: ToolCatalogItem[] = [
${toolTsRows}
];
`,
);

const toolManifest = tools.tools.map((tool) => ({
  name: tool.name,
  command: tool.human_equivalent,
  permission: tool.permission,
  approval: tool.approval,
  audit: tool.audit,
  availableTo: tool.available_to,
  mcp: tool.mcp,
  inputSchema: tool.input_schema,
  outputSchema: tool.output_schema,
  rateLimit: tool.rate_limit,
  bulkThreshold: tool.bulk_threshold ?? null,
}));
write("contracts/generated/tool-manifest.json", JSON.stringify(toolManifest, null, 2) + "\n");

const schemaFiles = fs.readdirSync(path.join(ROOT, "contracts/schemas")).filter((name) => name.endsWith(".json"));
function rewriteRefs(value) {
  if (Array.isArray(value)) return value.map(rewriteRefs);
  if (value && typeof value === "object") {
    const result = {};
    for (const [key, child] of Object.entries(value)) {
      if (key === "$ref" && typeof child === "string") {
        result[key] = `#/components/schemas/${child.replace(/\.json$/, "")}`;
      } else {
        result[key] = rewriteRefs(child);
      }
    }
    return result;
  }
  return value;
}

const openapiPaths = {};
for (const command of commandList) {
  const match = command.transports.http.match(/^(GET|POST|PATCH|PUT|DELETE) (\/api\/v1\/[^\s]+)$/);
  if (!match) throw new Error(`bad http ${command.transports.http}`);
  const [, method, route] = match;
  const operation = {
    operationId: command.name,
    summary: command.summary,
    tags: [command.domain],
    "x-command": command.name,
    "x-permission": command.permission,
    "x-requires-unlock": command.requiresUnlock,
    "x-audit": command.audit,
    responses: {
      200: {
        description: "DigiLegacy envelope",
        content: {
          "application/json": {
            schema: {
              type: "object",
              required: ["success", "code", "message", "data"],
              properties: {
                success: { type: "boolean" },
                code: { type: "string" },
                message: { type: "string" },
                data: { $ref: `#/components/schemas/${command.output.replace(/\.json$/, "")}` },
                details: { type: ["object", "null"] },
                traceId: { type: "string" },
              },
            },
          },
        },
      },
    },
  };
  const pathParams = [...route.matchAll(/\{([a-zA-Z0-9_]+)\}/g)].map((m) => m[1]);
  if (pathParams.length) {
    operation.parameters = pathParams.map((name) => ({
      name,
      in: "path",
      required: true,
      schema: { type: "string", minLength: 1 },
    }));
  }
  if (method !== "GET" && method !== "DELETE") {
    operation.requestBody = {
      required: true,
      content: {
        "application/json": {
          schema: { $ref: `#/components/schemas/${command.input.replace(/\.json$/, "")}` },
        },
      },
    };
  }
  openapiPaths[route] ??= {};
  openapiPaths[route][method.toLowerCase()] = operation;
}

const components = {};
for (const file of schemaFiles) {
  components[file.replace(/\.json$/, "")] = rewriteRefs(readJson(path.join("contracts/schemas", file)));
}
const openapi = {
  openapi: "3.1.0",
  info: {
    title: "DigiLegacy Platform API",
    version: "0.7.0-m0",
    description: "Generated from contracts/commands.json. M0 skeleton: read paths are declared, domain services land in M2.",
  },
  servers: [{ url: "http://127.0.0.1:8787", description: "Local platform server" }],
  paths: openapiPaths,
  components: { schemas: components },
};
write("contracts/openapi.json", JSON.stringify(openapi, null, 2) + "\n");

if (CHECK) {
  console.log(`contract check: ${commandList.length} commands, ${tools.tools.length} tools, ${schemaFiles.length} schemas, ${errorCodes.size} error codes`);
}
